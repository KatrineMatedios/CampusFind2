export interface ApiResponse<T> {
  data: T;
  message?: string;
}

export interface Paginated<T> {
  data: T[];
  links: {
    first: string | null;
    last: string | null;
    prev: string | null;
    next: string | null;
  };
  meta: {
    current_page: number;
    from: number | null;
    last_page: number;
    path: string;
    per_page: number;
    to: number | null;
    total: number;
  };
}

export interface ValidationErrors {
  message?: string;
  errors?: Record<string, string[]>;
}
